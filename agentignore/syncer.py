"""Synchronizer, generator, and diff engine for AI ignore files."""

from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple
import re

from agentignore.constants import (
    DEFAULT_BLOAT_PATTERNS,
    LOCKFILE_PATTERNS,
    SENSITIVE_PATTERNS,
    SUPPORTED_TARGETS,
    TARGET_FILENAME_MAP,
)
from agentignore.detector import detect_project_stacks, get_stack_patterns

GENERATED_HEADER_PREFIX = "# === Generated by agentignore ==="
CUSTOM_SECTION_MARKER = "# === Custom User Rules (Preserved) ==="


def extract_custom_rules(filepath: Path) -> List[str]:
    """Extract custom user rules from an existing ignore file."""
    if not filepath.exists() or not filepath.is_file():
        return []

    try:
        content = filepath.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return []

    # If the file contains our custom section marker, extract content under it
    if CUSTOM_SECTION_MARKER in content:
        parts = content.split(CUSTOM_SECTION_MARKER, 1)
        if len(parts) > 1:
            custom_part = parts[1].strip()
            return [
                line.strip()
                for line in custom_part.splitlines()
                if line.strip() and not line.strip().startswith("#")
            ]

    # If the file wasn't generated by agentignore, treat its non-empty non-comment lines as custom
    if GENERATED_HEADER_PREFIX not in content:
        lines = [line.strip() for line in content.splitlines()]
        return [l for l in lines if l and not l.startswith("#")]

    return []


def read_gitignore_patterns(repo_path: Path) -> List[str]:
    """Read cleaned non-comment patterns from .gitignore if present."""
    gitignore_path = repo_path / ".gitignore"
    if not gitignore_path.exists():
        return []

    patterns: List[str] = []
    try:
        with open(gitignore_path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                stripped = line.strip()
                if stripped and not stripped.startswith("#"):
                    patterns.append(stripped)
    except Exception:
        pass
    return patterns


def build_ignore_file_content(
    repo_path: Path,
    base_on_gitignore: bool = True,
    include_lockfiles: bool = False,
    extra_custom_rules: Optional[List[str]] = None,
) -> str:
    """Compile a comprehensive and standardized ignore specification."""
    stacks = detect_project_stacks(repo_path)
    stack_patterns = get_stack_patterns(stacks)

    sections: List[str] = []

    # Header
    sections.append(GENERATED_HEADER_PREFIX)
    sections.append(
        "# Universal AI Context Shield: Prevents secret leaks & token waste\n"
        "# Compatible with Cursor, Claude Code, Cline, Copilot, Windsurf, Aider, etc.\n"
        "# Run `agentignore sync` to update, or add custom rules at the bottom."
    )

    # 1. Critical Security & Secrets
    sections.append("\n# [1] Security & Secret Shields (Zero-leak policy)")
    seen: Set[str] = set()
    sec_lines = []
    for pat in SENSITIVE_PATTERNS:
        if pat not in seen:
            seen.add(pat)
            sec_lines.append(pat)
    sections.append("\n".join(sec_lines))

    # 2. Git-ignored Patterns
    if base_on_gitignore:
        git_patterns = read_gitignore_patterns(repo_path)
        if git_patterns:
            sections.append("\n# [2] Git-Ignored Rules (Mirrored from .gitignore)")
            git_lines = []
            for pat in git_patterns:
                if pat not in seen:
                    seen.add(pat)
                    git_lines.append(pat)
            if git_lines:
                sections.append("\n".join(git_lines))

    # 3. Stack-specific & General Bloat
    sections.append("\n# [3] AI Context Optimization (Bloat & Heavy Artifacts)")
    bloat_candidates = stack_patterns + DEFAULT_BLOAT_PATTERNS
    bloat_lines = []
    for pat in bloat_candidates:
        if pat not in seen:
            seen.add(pat)
            bloat_lines.append(pat)
    sections.append("\n".join(bloat_lines))

    # 4. Lockfiles
    if include_lockfiles:
        sections.append("\n# [4] Lockfiles (Large context token savers)")
        lock_lines = []
        for pat in LOCKFILE_PATTERNS:
            if pat not in seen:
                seen.add(pat)
                lock_lines.append(pat)
        sections.append("\n".join(lock_lines))
    else:
        sections.append(
            "\n# [4] Lockfiles (Uncomment to save 10k~100k tokens per query):\n"
            "# package-lock.json\n"
            "# pnpm-lock.yaml\n"
            "# yarn.lock\n"
            "# poetry.lock\n"
            "# Cargo.lock"
        )

    # 5. Custom User Rules Section
    custom_rules = list(extra_custom_rules or [])
    sections.append(f"\n{CUSTOM_SECTION_MARKER}")
    sections.append("# Add your custom project-specific rules below:")
    if custom_rules:
        sections.append("\n".join(custom_rules))

    return "\n".join(sections) + "\n"


def sync_repository(
    repo_path: Path,
    targets: Optional[List[str]] = None,
    dry_run: bool = False,
    include_lockfiles: bool = False,
) -> Dict[str, str]:
    """Sync compiled ignore rules to target AI ignore files."""
    if targets is None:
        targets = list(SUPPORTED_TARGETS.keys())

    # Gather custom rules from any existing files
    all_custom_rules: Set[str] = set()
    for name in targets:
        filename = TARGET_FILENAME_MAP.get(name)
        if filename:
            file_path = repo_path / filename
            for rule in extract_custom_rules(file_path):
                all_custom_rules.add(rule)

    content = build_ignore_file_content(
        repo_path=repo_path,
        base_on_gitignore=True,
        include_lockfiles=include_lockfiles,
        extra_custom_rules=sorted(list(all_custom_rules)),
    )

    results: Dict[str, str] = {}

    for name in targets:
        filename = TARGET_FILENAME_MAP.get(name)
        if not filename:
            continue

        target_path = repo_path / filename
        existed = target_path.exists()

        if existed:
            current_content = target_path.read_text(encoding="utf-8", errors="replace")
            if current_content == content:
                results[filename] = "unchanged"
                continue
            status = "updated"
        else:
            status = "created"

        if not dry_run:
            target_path.write_text(content, encoding="utf-8")

        results[filename] = status

    return results


def compute_ignore_diff(
    repo_path: Path, target_key: str = "cursor"
) -> Dict[str, List[str]]:
    """Compare .gitignore patterns with a target AI ignore file to show missing rules."""
    git_patterns = set(read_gitignore_patterns(repo_path))
    target_filename = TARGET_FILENAME_MAP.get(target_key, ".cursorignore")
    target_path = repo_path / target_filename

    target_patterns: Set[str] = set()
    if target_path.exists():
        try:
            with open(target_path, "r", encoding="utf-8", errors="replace") as f:
                for line in f:
                    stripped = line.strip()
                    if stripped and not stripped.startswith("#"):
                        target_patterns.add(stripped)
        except Exception:
            pass

    missing_in_target = sorted(list(git_patterns - target_patterns))
    unique_in_target = sorted(list(target_patterns - git_patterns))

    return {
        "missing_in_ai": missing_in_target,
        "unique_in_ai": unique_in_target,
    }
